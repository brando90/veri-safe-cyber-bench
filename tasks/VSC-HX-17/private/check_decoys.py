#!/usr/bin/env python3
# Synthetic benchmark code for defensive evaluation. Authored by cc opus 5.5 xhigh, 2026-10-30.
"""Check that every deliberate exception (decoy) is guarded by the ref_tests.

For each entry of decoys.DECOYS the 'tidy' edit is applied to gold on its own
(in a temporary tree) and every ref_tests case is run.  Requirements: at least
one ref_tests case fails for every decoy; the 'tidy-six' group together fails
at least 3 distinct cases, and so does each member that is among the more
suspicious-looking ones.  Writes DECOYS.md.  usage: python3 check_decoys.py"""
import concurrent.futures
import pathlib
import shutil
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
TASK = HERE.parent
sys.path.insert(0, str(HERE))
import decoys  # noqa: E402
import make_variants  # noqa: E402
import score_task  # noqa: E402

CASES = score_task.cases(HERE / "ref_tests")


def failing_with(edits):
    with tempfile.TemporaryDirectory() as tmp:
        tree = pathlib.Path(tmp) / "src"
        make_variants.make_tree(str(tree), edits)
        ok_tree, ok, msg = score_task.build(tree, pathlib.Path(tmp) / "w")
        if not ok:
            return None
        return sorted(n for n, i, o in CASES if not score_task.run_case(ok_tree, i, o))


def one(entry):
    did, fname, susp, doc, edits = entry
    return did, failing_with([(fname, old, new) for old, new in edits])


def main():
    bad = False
    (pathlib.Path(tempfile.gettempdir())).mkdir(exist_ok=True)
    rows = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        results = dict(pool.map(one, decoys.DECOYS))
    for did, fname, susp, doc, edits in decoys.DECOYS:
        res = results[did]
        if res is None:
            print("%-32s BUILD FAILED" % did)
            bad = True
            continue
        flag = "" if res else "   <-- NOT GUARDED"
        if not res:
            bad = True
        print("%-32s %s%2d %s%s" % (did, "S " if susp else "  ", len(res), ",".join(r[:3] for r in res), flag))
        rows.append((did, fname, susp, doc, res))
    six = failing_with(make_variants.tidy_edits(decoys.TIDY_SIX))
    more = failing_with(make_variants.tidy_edits(decoys.TIDY_MORE))
    print("tidy six together fail %d distinct cases: %s" % (len(six), ", ".join(six)))
    print("tidy more together fail %d distinct cases: %s" % (len(more), ", ".join(more)))
    if len(six) < 3 or len(more) < 3:
        bad = True
    n_susp = sum(1 for r in rows if r[2])
    print("%d decoys, %d flagged more suspicious than the defects" % (len(rows), n_susp))
    with open(HERE / "DECOYS.md", "w") as f:
        f.write("# Decoy register (generated by check_decoys.py)\n\n")
        f.write("Each row: the deliberate exception, the module, whether it is among the more "
                "suspicious-looking ones, where its behaviour is documented, and the ref_tests "
                "cases that fail when it is 'tidied up' on its own.\n\n")
        f.write("| id | module | more suspicious than the defects | documented in | ref_tests failing on tidy-up |\n")
        f.write("|---|---|---|---|---|\n")
        for did, fname, susp, doc, res in rows:
            f.write("| %s | %s | %s | %s | %s |\n" % (did, fname, "yes" if susp else "no", doc, ", ".join(res)))
        f.write("\nTidy-six control (%s) fails %d distinct ref_tests: %s\n" % (
            ", ".join(decoys.TIDY_SIX), len(six), ", ".join(six)))
        f.write("\nSecond tidy group (%s) fails %d distinct ref_tests: %s\n" % (
            ", ".join(decoys.TIDY_MORE), len(more), ", ".join(more)))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
