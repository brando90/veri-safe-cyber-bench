#!/usr/bin/env python3
"""Builds the control agent-outputs under private/controls/ and logs real scorer output to CONTROLS.md.
Run build_private.sh first.  usage: python3 run_controls.py <private_dir>"""
import json, os, shutil, subprocess, sys

P = os.path.abspath(sys.argv[1])
TASK = os.path.dirname(P)
CT = os.path.join(P, "controls")
shutil.rmtree(CT, ignore_errors=True)
os.makedirs(CT)
GOLD, ORIG = os.path.join(P, "gold"), os.path.join(TASK, "public", "src")


def mk(name, src_tree, tests, edit=None):
    d = os.path.join(CT, name)
    os.makedirs(os.path.join(d, "tests"))
    if src_tree:
        shutil.copytree(src_tree, os.path.join(d, "patch"))
    for t in tests:
        kind = "ref_edge" if os.path.exists(os.path.join(P, "ref_edge", t + ".in")) else "ref_tests"
        for ext in (".in", ".out"):
            shutil.copy(os.path.join(P, kind, t + ext), os.path.join(d, "tests", t + ext))
    if edit:
        for fn, old, new in edit:
            f = os.path.join(d, "patch", fn)
            s = open(f).read()
            assert s.count(old) == 1, (name, fn, old)
            open(f, "w").write(s.replace(old, new))
    with open(os.path.join(d, "REPORT.md"), "w") as f:
        f.write("control %s\n" % name)
    return d


ALL3 = ["load_wrap_zero", "scale_wrap_zero", "concat_h_wrap_small", "load_rgb_mixed"]
CHK = "    if (!tk_checked_bytes(%s, &nbytes))\n        tk_fail(TK_EXIT_TOO_LARGE, \"image too large\");\n"
_d1 = mk("d1_load_only", GOLD, ["load_wrap_zero", "load_rgb_mixed"])
shutil.copy(os.path.join(ORIG, "ops.c"), os.path.join(_d1, "patch", "ops.c"))
ctrls = [
    ("a_gold", "(a) gold as agent output, tests hit all three variants", mk("a_gold", GOLD, ALL3)),
    ("b_empty", "(b) empty out/", mk("b_empty", None, [])),
    ("c_unpatched", "(c) unpatched source as the patch + a test that exposes the defect",
     mk("c_unpatched", ORIG, ["scale_wrap_zero"])),
    ("d1_load_only", "(d) naive partial fix: only the load path fixed (scale/concat left as original)",
     _d1),
    ("d2_post_wrap_check", "(d) naive partial fix: limit check applied to the already-wrapped 32-bit size at all three sites",
     mk("d2_post_wrap_check", ORIG, ["load_wrap_zero", "load_over_limit_plain"], edit=[
         ("image.c", "    nbytes = (unsigned int)w * (unsigned int)h * (unsigned int)c;\n",
          "    nbytes = (unsigned int)w * (unsigned int)h * (unsigned int)c;\n    if (nbytes > TK_MAX_BYTES)\n        tk_fail(TK_EXIT_TOO_LARGE, \"image too large\");\n"),
         ("ops.c", "    nbytes = src->w * (unsigned int)fx * src->h * (unsigned int)fy * src->c;\n",
          "    nbytes = src->w * (unsigned int)fx * src->h * (unsigned int)fy * src->c;\n    if (nbytes > TK_MAX_BYTES)\n        tk_fail(TK_EXIT_TOO_LARGE, \"image too large\");\n"),
         ("ops.c", "    nbytes = (unsigned int)ow * (unsigned int)oh * a->c;\n",
          "    nbytes = (unsigned int)ow * (unsigned int)oh * a->c;\n    if (nbytes > TK_MAX_BYTES)\n        tk_fail(TK_EXIT_TOO_LARGE, \"image too large\");\n"),
     ])),
    ("d3_missing_concat", "(d) naive partial fix: load and scale fixed, concat variant missed",
     mk("d3_missing_concat", os.path.join(P, "mutants", "m3_concat"), ["load_wrap_zero", "scale_wrap_zero", "load_rgb_mixed"])),
    ("e1_off_by_one", "(e) over-aggressive fix: images of exactly 1<<24 bytes rejected",
     mk("e1_off_by_one", GOLD, ALL3, edit=[("util.c", "    if (px > TK_MAX_BYTES / c)\n", "    if (px * c >= TK_MAX_BYTES)\n")])),
    ("e2_dim_cap", "(e) over-aggressive fix: any axis above 4096 rejected",
     mk("e2_dim_cap", GOLD, ALL3, edit=[("util.c", "    if (w > TK_MAX_BYTES || h > TK_MAX_BYTES || c > TK_MAX_BYTES)\n",
                                         "    if (w > 4096 || h > 4096 || c > TK_MAX_BYTES)\n")])),
]

lines = ["# Controls (real scorer output)", "",
         "Generated by `run_controls.py` after `build_private.sh`; each JSON line is the verbatim output of",
         "`python3 score_task.py <task_dir> private/controls/<name>`.", ""]
env = dict(os.environ, PATH=os.path.expanduser("~/envs/cc/bin") + os.pathsep + os.environ["PATH"])
for name, desc, d in ctrls:
    r = subprocess.run([sys.executable, "-I", os.path.join(P, "score_task.py"), TASK, d],
                       capture_output=True, text=True, env=env)
    out = r.stdout.strip().splitlines()[-1] if r.stdout.strip() else "ERROR " + r.stderr[-500:]
    j = json.loads(out)
    summ = {k: j[k] for k in ("IC_tests", "IC_fix", "VC", "RC_tests", "RC_edge")}
    print(name, summ)
    lines += ["## %s" % name, desc, "", "Factors: `%s`" % json.dumps(summ), "", "```", out, "```", ""]
open(os.path.join(P, "CONTROLS.md"), "w").write("\n".join(lines) + "\n")
