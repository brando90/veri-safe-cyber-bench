def write(directory, cases):
    directory.mkdir(parents=True, exist_ok=True)
    for old in directory.glob("*.in"):
        old.unlink()
    for name, lines in cases.items():
        (directory / (name + ".in")).write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    write(TASK / "public" / "smoke", SMOKE)
    write(ROOT / "ref_tests", REF_TESTS)
    write(ROOT / "ref_edge", REF_EDGE)
    print("inputs: smoke %d, ref_tests %d, ref_edge %d" % (len(SMOKE), len(REF_TESTS), len(REF_EDGE)))


if __name__ == "__main__":
    main()
